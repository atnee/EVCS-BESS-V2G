"""Write the S3 config folder: a copy of configs/ plus the `s3_case:` overrides of configs/v2g.yaml.

python -m v2g.s3_configs --out results/configs_s3_final/A
python -m v2g.s3_configs --out results/configs_s3_final/B --variant B
The folder is meant for `integration.coordinator --configs <out>`; configs/ itself is never changed.
Every dotted key must already exist in the target YAML, so a typo cannot create a new key. Files with
overrides are rewritten with yaml.safe_dump (comments dropped; the commented source is configs/), the
others are copied byte for byte. <out>/S3_CHANGES.md lists every change. Depends only on pathlib,
shutil, yaml and argparse: no other project module.
"""
from pathlib import Path
import argparse
import shutil
import yaml


def load(path):
    with Path(path).open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def set_existing(tree, dotted, value):
    """Replace tree[a][b]... = value for dotted 'a.b...'; returns the old value. The key must exist."""
    *parents,last = dotted.split(".")
    node = tree
    for key in parents:
        if not isinstance(node,dict) or key not in node:
            raise ValueError(f"Unknown key {dotted!r}: {key!r} not found")
        node = node[key]
    if not isinstance(node,dict) or last not in node:
        raise ValueError(f"Unknown key {dotted!r}: {last!r} not found")
    old,node[last] = node[last],value
    return old


def changes_for(case, variant=None):
    """{file: {dotted key: value}} of the S3 case, with the variant applied on top."""
    files = {name: dict(keys) for name,keys in case["overrides"].items()}
    if variant is not None:
        variants = case.get("variants") or {}
        if variant not in variants:
            raise ValueError(f"Unknown S3 variant {variant!r}; available: {sorted(variants)}")
        for name,keys in variants[variant].items():
            files.setdefault(name,{}).update(keys)
    return files


def git_commit(start):
    """Short commit of the repository holding `start`, read from .git without running git; None if unknown."""
    for folder in [Path(start).resolve(),*Path(start).resolve().parents]:
        git = folder/".git"
        if git.is_dir():
            head = (git/"HEAD").read_text().strip()
            if not head.startswith("ref: "):
                return head[:7]
            ref = head[5:]
            if (git/ref).is_file():
                return (git/ref).read_text().strip()[:7]
            packed = git/"packed-refs"
            if packed.is_file():
                for line in packed.read_text().splitlines():
                    if line.endswith(" "+ref):
                        return line[:7]
            return None
        if git.is_file():
            return None  # worktree or submodule: not resolved here
    return None


def write_configs(out, configs="configs", variant=None):
    """Copy configs/*.yaml to out, apply the s3_case overrides (and variant); returns the change rows."""
    configs,out = Path(configs),Path(out)
    case = load(configs/"v2g.yaml").get("s3_case")
    if not case:
        raise ValueError(f"{configs/'v2g.yaml'} has no s3_case: block")
    files = changes_for(case,variant)
    sources = sorted(configs.glob("*.yaml"))
    missing = set(files)-{p.name for p in sources}
    if missing:
        raise ValueError(f"s3_case refers to files not in {configs}: {sorted(missing)}")
    out.mkdir(parents=True,exist_ok=True)
    rows = []
    for source in sources:
        if source.name not in files:
            shutil.copyfile(source,out/source.name)
            continue
        tree = load(source)
        for key,value in files[source.name].items():
            rows.append((source.name,key,set_existing(tree,key,value),value))
        with (out/source.name).open("w",encoding="utf-8") as f:
            yaml.safe_dump(tree,f,sort_keys=False,allow_unicode=True)
    lines = ["# S3 config folder (generated by `python -m v2g.s3_configs`; do not edit)", "",
             f"- Source: `{configs.as_posix()}` at commit `{git_commit(configs) or 'unknown'}`",
             f"- Variant: {variant or 'none (S3 case A)'}",
             "- Every other key and file is identical to the source.", "",
             "| File | Key | Official value | S3 value |", "|---|---|---|---|"]
    lines += [f"| `{name}` | `{key}` | `{old}` | `{new}` |" for name,key,old,new in rows]
    (out/"S3_CHANGES.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out",required=True,help="folder to write (created if missing)")
    parser.add_argument("--configs",default="configs",help="official config folder with the s3_case: block")
    parser.add_argument("--variant",default=None,help="optional variant of s3_case.variants (e.g. B)")
    args = parser.parse_args()
    rows = write_configs(args.out,args.configs,args.variant)
    print(f"{args.out}: {len(rows)} changed keys")
    for name,key,old,new in rows:
        print(f"  {name}: {key}: {old!r} -> {new!r}")


if __name__ == "__main__":
    main()
